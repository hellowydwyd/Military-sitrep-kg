class Slot(NamedTuple):
    """一个论元槽位。

    name   槽位名，如「打击方」
    types  允许的端点类型
    fill   必填程度：
             "req"  原文有就必须填，缺失视为漏抽
             "opt"  原文提到才填
             "cond" 条件必填，判据写在提示词里
    note   一句话说明，进提示词
    """

    name: str
    types: tuple[str, ...]
    fill: str
    note: str = ""


def S(name, types, fill="opt", note=""):
    return Slot(name, tuple(types), fill, note)


