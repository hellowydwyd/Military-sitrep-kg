"""事件论元（槽位）的唯一事实源。

设计原则
--------
1. **不用通用角色。** 每个二级类型声明一套封闭论元，不在表里的角色一律不允许。
   早期设「施事/受事/涉及 对所有类型开放」，实测导致同一事件里施事与甲方/表态方/主体
   重复填充（25 次并存中 15 次值完全相同），且约束口径在注释与代码间不一致。
2. **施动角色按类型起专名。** 打击方、拦截方、部署方、表态方、主办方、援助方……
   名字本身说明「这是什么动作的执行者」，避免一个「施事」承担十几种语义。
3. **每个槽位有显式的端点类型与是否必填。** 必填项缺失计入 recall 损失，便于度量。
4. **端点类型只有一处定义。** 提示词、校验、标注前端都从这里取，不再各自维护。

端点类型
--------
国家 / 机构 / 人物 / 装备 / 地点 / 作品 / 事件 / 字面值

字面值 = 从原文摘录的连续片段（数字、短语、原句），不是可复用实体。
"""

