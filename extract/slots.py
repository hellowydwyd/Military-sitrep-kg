def slot_notes(event_type: str, subtype: str) -> str:
    """生成某类型的槽位语义说明，供提示词或标注规范复用。"""
    out = []
    for s in slots_of(event_type, subtype):
        out.append(f"  {s.name} → {'/'.join(s.types)}（{s.note}）")
    return "\n".join(out)


