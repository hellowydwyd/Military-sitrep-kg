def slots_of(event_type: str, subtype: str) -> list[Slot]:
    """取某二级类型的槽位表。判不出二级时给空表，调用方自行兜底。"""
    if event_type == "其他" or not subtype:
        return OTHER[()] if event_type == "其他" else []
    table = SLOTS.get(event_type) or {}
    return table.get((subtype,)) or []


def slot_names(event_type: str, subtype: str) -> list[str]:
    return [s.name for s in slots_of(event_type, subtype)]


# ---------------------------------------------------------------- 派生视图

def _build_domain() -> dict[str, list[tuple[set[str], set[str]]]]:
    """槽位名 -> [(起点类型, 终点类型), ...]。

    同名可多义，按起点类型区分：例如「部署方」既是部署事件的施动论元
    （事件→机构），也是装备与机构的稳定关系（装备→机构）。校验时按头端点类型择一。
    """
    out: dict[str, list[tuple[set[str], set[str]]]] = {}

    def add(name: str, head: set[str], tail: set[str]) -> None:
        for h, t in out.get(name, []):
            if h == head and t == tail:
                return
        out.setdefault(name, []).append((head, tail))

    for table in (*SLOTS.values(), OTHER):
        for slots in table.values():
            for s in slots:
                add(s.name, {"事件"}, set(s.types))

    # 复合事件包含原子事件，不走事件槽位校验
    add("包含", {"事件"}, {"事件"})
    # 实体间稳定关系，归 RE
    add("隶属", {"机构", "国家"}, {"机构", "国家"})
    add("辖属", {"机构"}, {"国家"})
    add("驻地", {"机构"}, {"地点"})
    # 同名多义：装备由谁部署（与部署事件的「部署方」论元同义不同层）
    add("部署方", {"装备"}, {"机构", "国家"})
    add("去向", {"装备"}, {"地点", "国家"})
    add("任职", {"人物"}, {"机构", "国家"})
    add("会晤", {"人物"}, {"人物"})
    add("搭载", {"装备"}, {"装备"})
    add("位于", {"地点"}, {"地点"})
    add("敌对", {"机构"}, {"机构"})
    return out


DOMAIN = _build_domain()


def domain_of(name: str, head_type: str) -> tuple[set[str], set[str]] | None:
    """按关系名与头端点类型取允许多义中的一支。"""
    for head, tail in DOMAIN.get(name, []):
        if head_type in head:
            return head, tail
    return None

