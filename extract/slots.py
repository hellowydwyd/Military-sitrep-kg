def prompt_block() -> str:
    """生成提示词里的槽位说明段。单一来源，避免提示词与校验表漂移。"""
    lines = []
    for et in EVENT_TYPES:
        if et == "其他":
            continue
        lines.append(f"【{et}】")
        for sub in SUBTYPES[et]:
            slots = SLOTS[et].get((sub,)) or []
            if not slots:
                continue
            parts = []
            for s in slots:
                # * 必填；~ 条件必填（原文点到才填）；无标记为可选
                mark = "*" if s.fill == "req" else ("~" if s.fill == "cond" else "")
                parts.append(f"{s.name}{mark}→{'/'.join(s.types)}")
            lines.append(f"  {sub}：{'，'.join(parts)}")
        lines.append("")
    lines.append("【其他】（判不出上述二级时用，只填施动方与对象）")
    lines.append("  施动方→国家/机构/人物，对象→国家/机构/人物/地点/装备/作品")
